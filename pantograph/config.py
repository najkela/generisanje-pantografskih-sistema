"""Централизоване почетне вредности за калибрацију (BASELINE_SPEC §7).

Све вредности су ПОЧЕТНЕ, не коначне — калибришу се емпиријски (README 4.2). Држане на
једном месту да не буду расуте по модулима (BASELINE_SPEC §7).
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class Config:
    """Један комплет хиперпараметара за покретање (baseline или bilevel)."""

    population_size: int = 100
    total_budget: int = 50_000          # позива симулатора, идентично за оба метода

    n_min: int = 4                       # доња граница броја чворова
    n_max: int = 12                      # горња граница броја чворова
    n_init_choices: tuple[int, ...] = (5, 6, 7, 8)   # почетно n, равномерно

    p_topo: float = 0.30                 # вероватноћа тополошке мутације
    p_coord: float = 0.70                # вероватноћа координатне мутације

    p_add_node_a: float = 0.40           # избор оператора при тополошкој мутацији
    p_add_node_b: float = 0.25
    p_delete_node: float = 0.35

    # --- режим фиксног n (DECISIONS §26.3, оператор преповезивања) -------------------
    # Ако је постављено, n се НИКАД не мења (ни иницијализација ни мутација) — једини
    # тополошки потез постаје `operators.reconnect_node`, add_node/delete_node постају
    # недостижни. Намерно РАЗЛИЧИТО поље од `fixed_n_curve` испод (тај контролише
    # резолуцију криве N, потпуно другу ствар). `n_min`/`n_max` су у овом режиму без
    # дејства (не улазе ни у једну проверу — `_choose_topology_operator` се не позива).
    fixed_n_nodes: int | None = None
    # Подела вероватноће унутар `reconnect_node` између подпотеза „промена ослонца" и
    # „обртање знака" (комплемент = 1 − ово). Образложење: за чвор k постоји C(k,2) избора
    # пара ослонаца наспрам свега 2 избора знака — тежина прати величину категоричког
    # простора кроз који потез креће, НЕ геометријску „крупноћу" потеза (обртање знака је
    # геометријски крупнији — физички помера чвор и низводни ланац; промена ослонца чува
    # облик у θ=0 непромењен осим за сам чвор). Почетна и калибрациона вредност, као и све
    # остале из README 4.2 — не коначна.
    p_reconnect_anchor: float = 0.70

    gene_wise_prob: float = 0.25         # координатна мутација — вероватноћа по чвору
    k_start: float = 0.15                # скала координатне мутације — почетак
    k_end: float = 0.02                  # скала координатне мутације — крај (експоненцијално)

    alpha_min: float = 0.10              # add_node начин А (BASELINE_SPEC §4.1)
    alpha_max: float = 0.40
    rho_min: float = 0.7                 # add_node начин Б и иницијализација (§4.2, §8)
    rho_max: float = 1.3

    penalty: float = 1e9                 # казна за невалидну јединку
    fitness_cap: float = 1e8             # одсецање валидног фитнеса

    # праг угла преноса ∠(a–u–b) сваког чвора кроз пуну ротацију
    # (docs/NALAZ_01_09_ugao_prenosa.md, docs/NALAZ_01_09_poza.md, DECISIONS §17).
    # Ревидирано 02.09. са 5.0 на 10.0 после анализе расподеле углова. Мерено колико праг
    # стеже (удео тополошки валидних које заврше пун обртај): 5° → 80.7%, 10° → 73.6%,
    # 20° → 56.8%, 40° → 14.8% (литературних 40° за четворополужја би побило 85% популације).
    # Следећи разуман корак при ревизији је 20° — ОПРЕЗ: демо механизам из
    # `run.py::_demo_genome` (иста геометрија коју користи и
    # `tests/test_simulator.py::test_path_has_requested_resolution`) има минимални угао
    # преноса 18.4° кроз пун обртај — праг 10° прелази, праг 20° би га оборио заједно са
    # `run.py demo` и тим тестом. Ревизија на 20° мора то очекивати, не бити изненађена тиме.
    min_transmission_angle_deg: float = 10.0

    # Горња граница односа (largest_link) / (path_radius) (DECISIONS §17, ревидирано —
    # раније само дијагностика у логу). Под пуном скалном инваријантношћу фитнес не види
    # величину механизма у односу на криву коју црта, па претрага одлази у гломазна решења.
    # Ревидирано 03.09. са 10.0 на 5.0, мерено са ИСПРАВНО прослеђеним config-ом
    # (--quick на елипси, 3 seed-a): граница 10 → медијана Chamfer 3.93e-04, односи
    # 2.69/8.80/5.98, углови преноса 30°/14°/11°; граница 5 → медијана Chamfer 1.35e-04,
    # односи 4.64/4.84/4.24, углови преноса 40°/29°/31°. Граница 5 није скупља и остаје даље
    # од мртве тачке; почетна популација то подноси (73–82% решивих јединки већ испод 5,
    # мерено на 3 seed-а, популација 100).
    max_link_to_radius_ratio: float = 5.0

    n_schedule: tuple[int, ...] = (90, 180, 360, 720)
    plateau_window_grow: int = 15        # генерација, за напредовање N
    plateau_eps_grow: float = 0.01       # релативно побољшање
    plateau_window_stop: int = 30        # генерација, за заустављање на N=720
    plateau_eps_stop: float = 0.001

    # --- режим поређења (DECISIONS §24.2, имплементирано 14.09.) ---------------------
    # Фиксна резолуција: ако је постављено, `experiment.resolution_schedule` враћа ову
    # вредност у СВАКОЈ генерацији и распоред N се не примењује. У подразумеваном профилу
    # остаје None — распоред 90→180→360→720 ради како је и радио.
    fixed_n_curve: int | None = None
    # Рано заустављање ТОКА на плато (на највећем N). Гаси се у режиму поређења: тада је
    # једини критеријум краја потрошен буџет, па оба метода троше исто. НЕ дира плато
    # УНУТАР ЦМА-ЕС рана (`plateau_window_k`) — то је део метода који се пореди, не
    # правило заустављања тока.
    early_stop: bool = True
    # Корак решетке за криву грешка-по-позивима (README 3.2). Генерација није фер јединица
    # између метода (baseline ≈ 100 позива по генерацији, bilevel ≈ 2 900), па се крива
    # бележи на заједничкој решетки израженој у ПОЗИВИМА, једнакој за оба метода.
    grid_step: int = 500

    # --- bilevel (DECISIONS §22) — не утичу ни на један параметар baseline-а изнад ------

    outer_population: int = 20           # величина спољашње популације топологија
    cma_lambda: int | None = None        # None → подразумевано из `cma` (4 + 3·ln d)
    # Почетна ширина нових димензија при warm-start-у (§22 А4) — исти ред величине као
    # `cma_stds_gene`, нешто шире јер нова геометрија нема родитељски контекст.
    cma_sigma0_new: float = 0.3
    # Границе ρ димензија (В2). Проширене 05.09. (DECISIONS §24, А1) са [0.05, 20.0] на
    # [0.01, 100.0] — довољно широко да их законити оператори не могу пробити. Више нису
    # активно ограничење претраге (то ради тврда граница гломазности, §18), само
    # декларација коју `cma` конструктор захтева. ρ ван ЧАК и ове границе → невалидна
    # мутација (bilevel.py, `_construct_cma_es`), не clip.
    cma_rho_lower: float = 0.01
    cma_rho_upper: float = 100.0
    # Почетне ширине по координати за СВЕЖ ЦМА-ЕС (В4) — образложење: чвор 1 (q1) се
    # иницијализује из U(-1.5,1.5)², ручица (q2) на U(0.2,0.8) од чвора 0, а ρ живе око
    # U(0.7,1.3) — ширине прате те распоне (README 4.1).
    cma_stds_q1: tuple[float, float] = (0.6, 0.6)
    cma_stds_q2: tuple[float, float] = (0.3, 0.3)
    cma_stds_gene: tuple[float, float] = (0.15, 0.15)
    plateau_window_k: int = 10           # прозор плато-детекције УНУТАР ЦМА-ЕС рана (динамички K)
    plateau_eps_k: float = 0.01
    k_max: int = 200                     # горња граница итерација ЦМА-ЕС по процени топологије
    fixed_k: int | None = None           # ако постављено, игнорише плато — референтне 5/15/40 (H3)


DEFAULT_CONFIG = Config()


# Режим поређења (DECISIONS §24.2, одлучено 06.09., имплементирано 14.09.) — ДОПУНА
# подразумеваном профилу (§18), не замена. Фиксно N=720 за оба метода, фиксан буџет
# 100 000 позива, без раног заустављања на плато.
#
# Разлог: у подразумеваном профилу два конфаунда разликују методе из разлога који немају
# везе са H1 — растућа резолуција (baseline и bilevel је не прелазе истим темпом јер им
# генерација значи различиту ствар) и правило заустављања (baseline стаје на 24–42%
# буџета, bilevel троши све). Фиксирањем обоје остаје да се разликује само метод, па
# прва метрика из §8 постаје дословно тачна.
#
# Baseline референце измерене под подразумеваним профилом НИСУ упоредиве са овим режимом.
POREDJENJE_CONFIG = Config(
    total_budget=100_000,
    fixed_n_curve=720,
    early_stop=False,
)


# Демонстрациони профил (31.08.) — НИЈЕ мерење, не улази у H1 поређење.
# Мањи буџет и популација да покретање стане у минут, али и КРАЋИ плато-прозори:
# уз `plateau_window_grow=15` и стотинак генерација распоред N не би стигао даље од
# 180, па се адаптивна резолуција — једна од ствари које се показују — не би ни видела.
# Измерено 31.08. (100 јединки, circle): 2.1 ms/јединки на N=90, 16.0 ms на N=720.
QUICK_CONFIG = Config(
    population_size=30,
    total_budget=3_000,          # ≈100 генерација
    plateau_window_grow=5,
    plateau_window_stop=12,
    # bilevel-део профила (PROMPT_BILEVEL целина Г) — мања спољашња популација и краћи
    # унутрашњи плато-прозор, да `--quick` покретање стане у минут као и baseline-ов.
    outer_population=8,
    plateau_window_k=4,
    k_max=15,
)
